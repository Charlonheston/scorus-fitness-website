import { chromium } from '@playwright/test';
import { readFile, mkdir } from 'node:fs/promises';
const access=JSON.parse(await readFile('.scorus-deploy/access.private.json','utf8'));
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({httpCredentials:{username:access.panel_user,password:access.panel_password},viewport:{width:1440,height:1000}});
const page=await context.newPage();
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.goto('https://scorusfitness.com/scorus-gestion',{waitUntil:'networkidle'});
await page.getByRole('heading',{name:'SCORUS TEAM · Gestión'}).waitFor();
await page.getByText('Modo de pruebas · Los clientes reales').waitFor();
await mkdir('.scorus-deploy',{recursive:true});
await page.screenshot({path:'.scorus-deploy/scorus-panel.png',fullPage:true});
await page.goto('https://scorusfitness.com/es/scorus-team#valoracion',{waitUntil:'networkidle'});
await page.getByRole('heading',{name:'Tu próximo paso empieza aquí.'}).waitFor();
await page.getByLabel('Perder grasa',{exact:true}).check();
await page.getByLabel('Saber qué hacer y cómo progresar',{exact:true}).check();
await page.getByRole('button',{name:'Siguiente',exact:true}).click();
await page.getByLabel('Entreno con regularidad',{exact:true}).check();
await page.getByLabel('En un gimnasio',{exact:true}).check();
await page.getByLabel('3 días',{exact:true}).check();
await page.getByLabel('Entre 30 y 45 minutos',{exact:true}).check();
await page.getByRole('button',{name:'Siguiente',exact:true}).click();
await page.getByRole('textbox',{name:'Tu nombre'}).waitFor();
await page.screenshot({path:'.scorus-deploy/scorus-form.png',fullPage:false});
if(errors.length)throw Error(errors.join('\n'));
console.log('Panel privado y formulario: verificados sin enviar datos ni WhatsApps.');
await browser.close();
